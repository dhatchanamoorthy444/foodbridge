import { Router, Request, Response, NextFunction } from 'express'
import { authMiddleware } from '../middleware/auth'
import { supabaseAdmin } from '../db/supabase'
import { NotificationRow } from '../types/db'

const router = Router()
router.use(authMiddleware)

router.get('/', async (req: Request, res: Response, next: NextFunction) => {
  try {
    const limit = Math.min(Number(req.query.limit ?? 40), 100)
    const { data, error, count } = await supabaseAdmin
      .from('notifications')
      .select('*', { count: 'exact' })
      .eq('user_id', req.user!.userId)
      .order('created_at', { ascending: false })
      .limit(limit)
    if (error) throw error
    const unread = (data ?? []).filter((n: NotificationRow) => !n.read).length
    res.json({ data, unread: Math.max(unread, 0), total: count ?? 0 })
  } catch (e) {
    next(e)
  }
})

router.patch(
  '/:id/read',
  async (req: Request, res: Response, next: NextFunction) => {
    try {
      const { data, error } = await supabaseAdmin
        .from('notifications')
        .update({ read: true })
        .eq('id', req.params.id)
        .eq('user_id', req.user!.userId)
        .select('id')
      if (error) throw error
      if (!data || data.length === 0) {
        return res.status(404).json({ error: 'Notification not found' })
      }
      return res.json({ ok: true })
    } catch (e) {
      next(e)
    }
  }
)

router.patch('/read-all', async (req, res, next) => {
  try {
    const { error } = await supabaseAdmin
      .from('notifications')
      .update({ read: true })
      .eq('user_id', req.user!.userId)
      .eq('read', false)
    if (error) throw error
    res.json({ ok: true })
  } catch (e) {
    next(e)
  }
})

// internal free-form create is disabled; messages are generated by events
router.post('/', (_req: Request, res: Response) => {
  res.status(405).json({
    error: 'Notifications are generated by system events only',
  })
})

export { router as notificationRoutes }
